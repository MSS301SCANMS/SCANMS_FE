import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const backend = path.resolve(root, '../SCANMS_BE');
const files = [];
function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const name = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(name);
    else if (entry.name.endsWith('.java')) files.push(name);
  }
}
for (const module of ['user', 'product', 'order', 'payment', 'promotion']) {
  const service = module === 'promotion' ? 'promotion-affiliate-service' : `${module}-service`;
  walk(path.join(backend, service, 'src/main/java'));
}
const enums = new Map();
const records = [];
for (const file of files.sort()) {
  const source = fs.readFileSync(file, 'utf8');
  const enumeration = source.match(/public enum (\w+)\s*\{([^}]+)\}/s);
  if (enumeration && /[\\/]constant[\\/]/.test(file)) enums.set(enumeration[1], enumeration[2].trim().split(/\s*,\s*/));
  if (/dto[\\/](request|response|ai)[\\/]/.test(file)) {
    const record = source.match(/public record (\w+)\s*\(([\s\S]*?)\)\s*\{/);
    // Some endpoints use mutable Java DTO classes. This generator emits record
    // contracts only; class DTOs must be handled explicitly by their callers.
    if (!record) continue;
    const body = record[2].replace(/@[\w.]+(?:\([^)]*\))?\s*/g, annotation => /@(NotNull|NotBlank|NotEmpty)\b/.test(annotation) ? ' REQUIRED ' : '');
    const fields = body.split(/,(?![^<]*>)/).map(value => {
      const required = value.includes('REQUIRED');
      const field = value.replace(/REQUIRED/g, '').trim().match(/^(.+)\s+(\w+)$/s);
      if (!field) throw new Error(`Unsupported field: ${file}: ${value}`);
      return { type: field[1].trim(), name: field[2], required };
    });
    records.push({ name: record[1], fields, request: file.includes(`${path.sep}request${path.sep}`) });
  }
}
function typeOf(type) {
  if (['String', 'Instant', 'LocalDateTime'].includes(type)) return 'string';
  if (['Long', 'Integer', 'int', 'long', 'double', 'Double'].includes(type)) return 'number';
  if (type === 'BigDecimal') return 'number | string';
  if (type === 'boolean' || type === 'Boolean') return 'boolean';
  if (type.startsWith('Map<')) return 'Record<string, unknown>';
  if (/^(List|Set)</.test(type)) return `${typeOf(type.slice(type.indexOf('<') + 1, -1))}[]`;
  if (enums.has(type) || records.some(record => record.name === type)) return type;
  throw new Error(`Unknown Java type: ${type}`);
}
let output = '// Generated by scripts/sync-backend-contracts.mjs. Do not edit by hand.\n';
for (const [name, values] of enums) output += `export type ${name} = ${values.map(v => JSON.stringify(v)).join(' | ')};\n`;
for (const record of records) {
  output += `\nexport interface ${record.name} {\n`;
  for (const field of record.fields) {
    const required = field.required || ['boolean', 'int', 'long', 'double'].includes(field.type);
    output += `  ${field.name}${record.request && !required ? '?' : ''}: ${typeOf(field.type)}${required ? '' : ' | null'};\n`;
  }
  output += '}\n';
}
output += '\nexport interface BackendEnvelope<T> { code: number; message: string; result: T; }\n';
const target = path.join(root, 'src/types/backend.generated.ts');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Backend DTOs changed. Run npm run contracts:sync.');
  console.log(`Verified ${records.length} DTOs and ${enums.size} enums against SCANMS_BE.`);
} else {
  fs.writeFileSync(target, output);
  console.log(`Generated ${records.length} DTOs and ${enums.size} enums.`);
}
